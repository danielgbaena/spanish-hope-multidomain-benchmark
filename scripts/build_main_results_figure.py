import pandas as pd
import matplotlib.pyplot as plt

# =========================================================
# LOAD RESULTS
# =========================================================

df = pd.read_csv("results/final_results_summary.csv")

# =========================================================
# SORT BY PERFORMANCE
# =========================================================

df = df.sort_values(
    by="overall_macro_f1_mean",
    ascending=False
)

# =========================================================
# DATA
# =========================================================

models = df["model"]
scores = df["overall_macro_f1_mean"]

# =========================================================
# FIGURE
# =========================================================

plt.figure(figsize=(10, 6))

bars = plt.bar(
    models,
    scores
)

# =========================================================
# LABELS
# =========================================================

plt.ylabel("Macro-F1")
plt.xlabel("Model")

plt.title(
    "Cross-domain Macro-F1 Performance Across Models"
)

# =========================================================
# Y LIMITS
# =========================================================

plt.ylim(0.0, 0.85)

# =========================================================
# VALUE LABELS
# =========================================================

for bar, value in zip(bars, scores):

    plt.text(
        bar.get_x() + bar.get_width() / 2,
        value + 0.01,
        f"{value:.3f}",
        ha="center",
        fontsize=10
    )

# =========================================================
# GRID
# =========================================================

plt.grid(
    axis="y",
    linestyle="--",
    alpha=0.4
)

# =========================================================
# LAYOUT
# =========================================================

plt.tight_layout()

# =========================================================
# SAVE FIGURE
# =========================================================

output_path = "results/main_results_figure.pdf"

plt.savefig(
    output_path,
    bbox_inches="tight"
)

print("\n========================================")
print("Figure generated successfully.")
print("========================================")

print(f"\nSaved to:\n{output_path}")

print("\n========================================")
print("Done.")
print("========================================")
